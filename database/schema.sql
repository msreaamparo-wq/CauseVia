CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    username VARCHAR(100) UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password TEXT NOT NULL,
    batch_year VARCHAR(30),
    course VARCHAR(100),
    role VARCHAR(30) NOT NULL DEFAULT 'alumni',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    project_title VARCHAR(255) NOT NULL,
    category_name VARCHAR(100),
    description TEXT,
    target_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    current_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    start_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    end_date DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    cover_photo TEXT
);

CREATE TABLE IF NOT EXISTS donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    project_id BIGINT REFERENCES projects(id),
    amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    payment_method VARCHAR(50),
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    transaction_ref TEXT,
    payment_proof TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    message TEXT
);

CREATE TABLE IF NOT EXISTS general_donation (
    general_donation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    donation_type VARCHAR(50),
    amount NUMERIC(14,2) DEFAULT 0,
    payment_method VARCHAR(50),
    reference_number TEXT,
    proof TEXT,
    item_description TEXT,
    quantity NUMERIC(14,2),
    unit VARCHAR(50),
    message TEXT,
    status VARCHAR(30) DEFAULT 'pending',
    donation_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_projects_user_id ON projects(user_id);
CREATE INDEX IF NOT EXISTS idx_donations_user_id ON donations(user_id);
CREATE INDEX IF NOT EXISTS idx_donations_project_id ON donations(project_id);
CREATE INDEX IF NOT EXISTS idx_general_donation_user_id ON general_donation(user_id);
